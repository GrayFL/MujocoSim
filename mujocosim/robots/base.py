"""Two structural interfaces; implementations need not inherit a base class."""
from typing import Any, Protocol
import xml.etree.ElementTree as ET


class RobotState(Protocol):
    body_id: int

    def reset(self, spawn) -> None: ...
    def after_reset(self) -> None: ...
    def apply(self, command: Any) -> Any: ...
    def stop(self) -> None: ...
    def after_step(self) -> None: ...
    def telemetry(self) -> dict: ...


class Robot(Protocol):
    clearance_radius: float

    def build(self, root: ET.Element) -> ET.Element:
        """Append MJCF; return the body on which optional sensors mount."""
        ...

    def bind(self, model, data) -> RobotState: ...
